export type StringKey = keyof (typeof strings)["en"];

export function t(
  lang: "en" | "hi",
  key: StringKey,
  vars?: Record<string, string | number>
): string {
  let str: string = strings[lang][key] ?? strings.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
